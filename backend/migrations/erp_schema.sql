-- ============================================================================
-- LEF ERP — Finance / Inventory / Procurement / Administration schema
-- ----------------------------------------------------------------------------
-- Idempotent: every table uses CREATE TABLE IF NOT EXISTS and every seed row
-- uses INSERT IGNORE, so this file is safe to run repeatedly.
--
-- Design notes:
--  * No hard foreign keys to the EXISTING HR tables (users, employees,
--    departments, roles) because their column types are defined on the live
--    server and we must not risk a type-mismatch failure. We store their ids
--    as VARCHAR and index them instead. Existing HR logic is untouched.
--  * Master records use VARCHAR primary keys generated by controllers as
--    `PREFIX${Date.now()}` (matching the existing departments/employees style).
--  * High-volume line items and logs use BIGINT AUTO_INCREMENT.
-- ============================================================================

-- =====================  FINANCE  ============================================

CREATE TABLE IF NOT EXISTS expense_categories (
  id           VARCHAR(60) PRIMARY KEY,
  name         VARCHAR(120) NOT NULL,
  type         VARCHAR(40) DEFAULT 'operational',
  is_active    TINYINT(1) DEFAULT 1,
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS expenses (
  id             VARCHAR(60) PRIMARY KEY,
  ref            VARCHAR(40),
  category_id    VARCHAR(60),
  department_id  VARCHAR(60),
  vendor_id      VARCHAR(60),
  project        VARCHAR(120),
  payment_method VARCHAR(40) DEFAULT 'bank_transfer',
  amount         DECIMAL(14,2) DEFAULT 0,
  tax            DECIMAL(14,2) DEFAULT 0,
  total          DECIMAL(14,2) DEFAULT 0,
  currency       VARCHAR(8) DEFAULT 'GHS',
  expense_date   DATE,
  status         ENUM('draft','pending','approved','rejected','paid') DEFAULT 'pending',
  receipt_url    VARCHAR(255),
  invoice_url    VARCHAR(255),
  notes          TEXT,
  created_by     VARCHAR(60),
  approved_by    VARCHAR(60),
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_exp_cat (category_id), INDEX idx_exp_dept (department_id),
  INDEX idx_exp_status (status), INDEX idx_exp_date (expense_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

