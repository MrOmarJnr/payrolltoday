  moved_by          VARCHAR(60),
  movement_date     DATE,
  created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_mov_item (item_id), INDEX idx_mov_type (type), INDEX idx_mov_date (movement_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

