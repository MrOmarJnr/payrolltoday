  station          VARCHAR(120),
  fuel_type        VARCHAR(40) DEFAULT 'Petrol',
  litres           DECIMAL(12,2) DEFAULT 0,
  price_per_litre  DECIMAL(12,2) DEFAULT 0,
  amount           DECIMAL(14,2) DEFAULT 0,
  prev_odometer    INT DEFAULT 0,
  current_odometer INT DEFAULT 0,
  receipt_url      VARCHAR(255),
  log_date         DATE,
  status           ENUM('pending','approved','rejected') DEFAULT 'pending',
  approved_by      VARCHAR(60),
  notes            TEXT,
  created_by       VARCHAR(60),
  created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_fuel_dept (department_id), INDEX idx_fuel_date (log_date)
